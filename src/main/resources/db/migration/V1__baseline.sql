    ADD CONSTRAINT fk_movil_grupo FOREIGN KEY (id) REFERENCES grupos_electrogenos;
ALTER TABLE solicitudes_compra
    ADD CONSTRAINT fk_solicitud_entidad FOREIGN KEY (entidad_id) REFERENCES entidades;
ALTER TABLE solicitudes_compra
    ADD CONSTRAINT fk_solicitud_grupo FOREIGN KEY (grupo_id) REFERENCES grupos_electrogenos;
ALTER TABLE usuarios_roles
    ADD CONSTRAINT fk_usuarios_roles_role FOREIGN KEY (role_id) REFERENCES roles;
ALTER TABLE usuarios_roles
    ADD CONSTRAINT fk_usuarios_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios;
